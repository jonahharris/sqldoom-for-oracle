"""Export the gameplay catalogs the game tic needs (beyond the render catalogs in
03_catalogs.sql) from the CedarDB reference into oracle/sql/07b_game_catalogs.sql.

The reference seeds them in reference/sqldoom/sql/loader/game_data.sql; exporting
the loaded rows keeps them byte-for-byte what CedarDB runs with (doubles printed
with repr, so they round-trip exactly). Run once; the generated file is checked in
and needs no CedarDB to install.

Usage: export_game_catalogs.py [--dsn postgresql://...]
"""
import argparse
from pathlib import Path
import psycopg2

OUT = Path(__file__).resolve().parents[1] / "sql" / "07b_game_catalogs.sql"
# phase 4: the flow/screen catalogs (sql/loader/menu_data.sql, game_data.sql finale_defs)
OUT_FLOW = Path(__file__).resolve().parents[1] / "sql" / "07e_flow_catalogs.sql"
FLOW_TABLES = [("menu_items", "menu_items", {}), ("menu_decor", "menu_decor", {}),
               ("finale_defs", "finale_defs", {})]
DSN = "postgresql://postgres:postgres_doom_reference_pw@localhost:55433/postgres"
# (cedar table, oracle table, column renames)
TABLES = [
    ("doom_constants", "doom_constants", {}),
    ("pickup_defs", "pickup_defs", {}),
    ("pickup_messages", "pickup_messages", {}),
    ("chase_dir_defs", "chase_dir_defs", {}),
    ("thing_role_defs", "thing_role_defs", {}),
    ("thing_blocking_defs", "thing_blocking_defs", {}),
    ("sector_special_defs", "sector_special_defs", {}),
    ("thing_sound_defs", "thing_sound_defs", {}),
    ("level_pars", "level_pars", {"level": "lvl"}),
    ("boss_actions", "boss_actions", {}),
]


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, float):
        return repr(v) + "d"
    if isinstance(v, int):
        return str(v)
    # newlines as CHR(10): the scripts are split on ';' outside literals, line by line
    return " || CHR(10) || ".join("'" + part.replace("'", "''") + "'" for part in str(v).split("\n"))


def export(cur, tables, out, what):
    lines = ["-- Generated by oracle/client/export_game_catalogs.py from the CedarDB reference.",
             f"-- {what}", ""]
    for src, dst, ren in tables:
        cur.execute(f"SELECT * FROM {src} WHERE false")
        cols = [d.name for d in cur.description]
        sel = ", ".join(f"{c}::text" if d.type_code not in (16, 20, 21, 23, 700, 701, 1700) else c
                        for c, d in zip(cols, cur.description))
        cur.execute(f"SELECT {sel} FROM {src} ORDER BY 1, 2")
        rows = cur.fetchall()
        ocols = ", ".join(ren.get(c, c) for c in cols)
        lines.append(f"DELETE FROM {dst};")
        for r in rows:
            vals = []
            for v, d in zip(r, cur.description):
                if d.type_code in (700, 701, 1700) and v is not None:
                    v = float(v)
                vals.append(lit(v))
            lines.append(f"INSERT INTO {dst} ({ocols}) VALUES ({', '.join(vals)});")
        lines.append("")
    lines.append("COMMIT;")
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", default=DSN)
    ap.add_argument("--flow-only", action="store_true", help="only 07e_flow_catalogs.sql")
    args = ap.parse_args()
    cur = psycopg2.connect(args.dsn).cursor()
    if not args.flow_only:
        export(cur, TABLES, OUT, "Gameplay catalogs the game tic reads that 03_catalogs.sql does not load.")
    export(cur, FLOW_TABLES, OUT_FLOW, "Menu layout and finale texts (screens, phase 4).")


if __name__ == "__main__":
    main()
