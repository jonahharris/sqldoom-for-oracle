"""Assemble sql/render_optimized.sql (one SELECT) from the readable parts in sql/parts/."""
from pathlib import Path
D = Path(__file__).resolve().parent
parts = ["opt_frontend.sql", "opt_background.sql", "hud.sql", "opt_pixels.sql"]
body = []
for i, p in enumerate(parts):
    t = (D / "parts" / p).read_text().strip()
    if p == "hud.sql":
        t = t + ","
    body.append(t)
head = ("-- @output packed\n-- GENERATED by sql/build_optimized.py from sql/parts/*.sql -- edit the parts.\n"
        "-- Optimized Oracle renderer: one prepared SELECT; binds :tic :map_id :player_id :skill :px :py :pz :pangle.\n")
import re
text = "\n".join(body)
mat = [l.strip() for l in (D / "parts" / "materialize.txt").read_text().splitlines()
       if l.strip() and not l.startswith("#")]
for name in mat:
    m = re.search(r"(?m)^" + name + r" AS \(\s*(--[^\n]*\s*)*SELECT", text)
    assert m, name
    text = text[:m.end()] + " /*+ MATERIALIZE */" + text[m.end():]
(D / "render_optimized.sql").write_text(head + "WITH\n" + text + "\n")
print("wrote", D / "render_optimized.sql", sum(t.count("\n") for t in body), "lines")
