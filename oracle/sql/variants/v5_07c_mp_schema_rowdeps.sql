-- =============================================================================
-- 07c_mp_schema.sql -- deathmatch state (CedarDB 39_mp.sql / 42_api.sql tables)
--
-- g_mp_match         the match as a row (vanilla's command line: -timer, -altdeath,
--                    -nomonsters, -respawn)
-- g_mp_players       one slot per player start of the map; role_name = who holds it
-- g_mp_join_requests a slot claimed since the last tic (the tic respawns it)
-- g_mp_inputs        input rows the clients appended since the last tic
-- REAL -> BINARY_FLOAT as everywhere in the game schema. Timestamps are kept for the
-- referee's housekeeping (idle reaping) and never read by the tic.
-- Phase 5: the referee runs the tic SERIALIZABLE while the players' sessions insert input rows and
-- join requests; ROWDEPENDENCIES (a commit SCN per row) lets Oracle check the tic's DELETE of
-- those rows row by row -- with block-level SCNs it raised ORA-08177 whenever a player had
-- inserted into the same block after the tic began (probe: 116 of 190 tics, 0 with it).
-- =============================================================================
DROP TABLE IF EXISTS g_mp_match PURGE;
CREATE TABLE g_mp_match (
  id                 NUMBER(10)  DEFAULT 0 NOT NULL,
  map_id             NUMBER(10)  NOT NULL,
  skill              NUMBER(10)  DEFAULT 3 NOT NULL,
  state              VARCHAR2(16) DEFAULT 'playing' NOT NULL,
  timer_tics         NUMBER(10)  DEFAULT 21000 NOT NULL,
  altdeath           BOOLEAN     DEFAULT TRUE NOT NULL,
  monsters           BOOLEAN     DEFAULT TRUE NOT NULL,
  respawn_monsters   BOOLEAN     DEFAULT TRUE NOT NULL,
  intermission_tics  NUMBER(10)  DEFAULT 350 NOT NULL,
  intermission_until TIMESTAMP WITH TIME ZONE,
  maps_played        NUMBER(10)  DEFAULT 0 NOT NULL,
  hold_seconds       NUMBER(10)  DEFAULT 0 NOT NULL,
  CONSTRAINT g_mp_match_pk PRIMARY KEY (id)
);

DROP TABLE IF EXISTS g_mp_players PURGE;
CREATE TABLE g_mp_players (
  map_id          NUMBER(10)    NOT NULL,
  slot            NUMBER(10)    NOT NULL,
  player_thing_id NUMBER(10)    NOT NULL,
  skill           NUMBER(10)    DEFAULT 3 NOT NULL,
  role_name       VARCHAR2(128),
  pose_x          BINARY_FLOAT  DEFAULT 0 NOT NULL,
  pose_y          BINARY_FLOAT  DEFAULT 0 NOT NULL,
  pose_z          BINARY_FLOAT  DEFAULT 41 NOT NULL,
  pose_angle      BINARY_FLOAT  DEFAULT 0 NOT NULL,
  last_seen       TIMESTAMP WITH TIME ZONE,
  display_name    VARCHAR2(128),
  claimed_at      TIMESTAMP WITH TIME ZONE,
  CONSTRAINT g_mp_players_pk PRIMARY KEY (map_id, slot)
);
CREATE INDEX g_mp_players_p ON g_mp_players (map_id, player_thing_id);
-- a role holds at most one slot (phase 5: api_join's guard against a concurrent second claim)
CREATE UNIQUE INDEX g_mp_players_role ON g_mp_players (role_name);

DROP TABLE IF EXISTS g_mp_join_requests PURGE;
CREATE TABLE g_mp_join_requests (
  map_id NUMBER(10) NOT NULL,
  slot   NUMBER(10) NOT NULL,
  CONSTRAINT g_mp_join_requests_pk PRIMARY KEY (map_id, slot)
) ROWDEPENDENCIES;

DROP TABLE IF EXISTS g_mp_inputs PURGE;
CREATE TABLE g_mp_inputs (
  seq              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (CACHE 1000) NOT NULL,
  map_id           NUMBER(10)   NOT NULL,
  player_thing_id  NUMBER(10)   NOT NULL,
  move_fwd         BINARY_FLOAT DEFAULT 0 NOT NULL,
  move_strafe      BINARY_FLOAT DEFAULT 0 NOT NULL,
  running          BOOLEAN      DEFAULT FALSE NOT NULL,
  turn_degrees     BINARY_FLOAT DEFAULT 0 NOT NULL,
  attack_held      BOOLEAN      DEFAULT FALSE NOT NULL,
  weapon_switch_to NUMBER(10),
  use_requested    BOOLEAN      DEFAULT FALSE NOT NULL,
  CONSTRAINT g_mp_inputs_pk PRIMARY KEY (seq)
) ROWDEPENDENCIES;
CREATE INDEX g_mp_inputs_p ON g_mp_inputs (map_id, player_thing_id, seq);
